export type BrandAssetId = keyof typeof brandAssets;
export function normalizeBrandLabel(value: string) {
  return value.trim().replace(/\s+/g, " ").replace(/…/g, "...").replace(/[’‘]/g, "'").toLocaleUpperCase("ru-RU");
}
const byLabel = new Map<string, BrandAssetId>();
for (const id of Object.keys(brandAssets) as BrandAssetId[]) {
  const asset = brandAssets[id];
  for (const text of [asset.label, asset.display]) {
    const key = normalizeBrandLabel(text);
    if (!byLabel.has(key)) byLabel.set(key, id);
  }
}
export function findBrandAsset(label: string): BrandAssetId | undefined { return byLabel.get(normalizeBrandLabel(label)); }
